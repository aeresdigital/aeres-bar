public enum BrandMark {
    /// Outline in the mark's own SVG coordinates (y grows downwards).
    public static func path(for provider: ProviderID) -> Path {
        paths[provider] ?? Path()
    }

    /// Width / height of the mark.
    public static func aspectRatio(for provider: ProviderID) -> CGFloat {
        let bounds = path(for: provider).boundingRect
        return bounds.height > 0 ? bounds.width / bounds.height : 1
    }

    private static let paths: [ProviderID: Path] = {
        var result: [ProviderID: Path] = [:]
        for provider in ProviderID.allCases {
            let outlines = pathData(for: provider).compactMap { try? SVGPath.parse($0) }
                // Marks drawn with the even-odd rule get their holes resolved, so the union and the
                // default fill keep them open.
                .map { usesEvenOdd(provider) ? $0.normalized(using: .evenOdd) : $0 }
            guard var merged = outlines.first else { continue }
            // Separate SVG <path> elements are filled independently: merge them as a union.
            for outline in outlines.dropFirst() { merged = merged.union(outline) }
            result[provider] = Path(merged)
        }
        return result
    }()

